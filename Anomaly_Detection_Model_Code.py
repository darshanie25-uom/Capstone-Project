val_df = df[
    (df['date'] == '2026-03-05')
].copy()

# Remove Nulls from Training
train_df = train_df.dropna(
    subset=['sum_dl_traffic_volume_gb']
)

# Paramaters
LOOKBACK = 24
ANOMALY_THRESHOLD = 1

# Store Results
results = []
anomaly_list = []
forecasts = {}

# LIimit Number of Sites
site_list = train_df['site_name'].unique()[:50]

# Train Model per Site
for site in site_list:

    print(f"Processing Site: {site}")

    # Site Data
    site_train = train_df[
        train_df['site_name'] == site
    ].sort_values('datetime')

    site_val = val_df[
        val_df['site_name'] == site
    ].sort_values('datetime')

    # Skip weak sites
    if len(site_train) < LOOKBACK + 5:
        continue

    if len(site_val) == 0:
        continue

    try:

        # Target Series
        train_series = (
            site_train['sum_dl_traffic_volume_gb']
            .values
            .reshape(-1, 1)
        )

        # Scaling
        scaler = MinMaxScaler()

        train_scaled = scaler.fit_transform(
            train_series
        )

        # Create Sequences
        X_train = []
        y_train = []

        for i in range(LOOKBACK, len(train_scaled)):

            X_train.append(
                train_scaled[
                    i-LOOKBACK:i
                ]
            )

            y_train.append(
                train_scaled[i]
            )

        X_train = np.array(X_train)
        y_train = np.array(y_train)

        # Build light weight LSTM Model
        model = Sequential()

        model.add(
            LSTM(
                16,
                input_shape=(LOOKBACK, 1)
            )
        )

        model.add(Dense(1))

        model.compile(
            optimizer='adam',
            loss='mse'
        )

        # Train Model
        model.fit(
            X_train,
            y_train,
            epochs=5,
            batch_size=16,
            verbose=0
        )

        # Forecasting
        history = train_scaled[-LOOKBACK:]

        predictions = []

        for i in range(len(site_val)):

            X_input = history.reshape(
                1,
                LOOKBACK,
                1
            )

            y_pred_scaled = model.predict(
                X_input,
                verbose=0
            )

            y_pred = scaler.inverse_transform(
                y_pred_scaled
            )[0][0]

            predictions.append(y_pred)

            history = np.append(
                history[1:],
                y_pred_scaled
            )

        # Store Forecasts
        forecast_df = site_val[
            ['datetime']
        ].copy()

        forecast_df['PredictedTraffic'] = (
            predictions
        )

        forecast_df['ActualTraffic'] = (
            site_val[
                'sum_dl_traffic_volume_gb'
            ].values
        )

        forecasts[site] = forecast_df

        # Metrics
        merged = forecast_df.dropna()

        if len(merged) == 0:
            continue

        mae = mean_absolute_error(
            merged['ActualTraffic'],
            merged['PredictedTraffic']
        )

        rmse = np.sqrt(
            mean_squared_error(
                merged['ActualTraffic'],
                merged['PredictedTraffic']
            )
        )

        r2 = r2_score(
            merged['ActualTraffic'],
            merged['PredictedTraffic']
        )

        results.append({
            'site_name': site,
            'MAE': mae,
            'RMSE': rmse,
            'R2': r2
        })

        # Anomaly Detection
        merged['is_null_anomaly'] = (
            merged['ActualTraffic'].isnull()
        )

        merged = merged[
            merged['PredictedTraffic'] != 0
        ]

        merged['deviation'] = (
            abs(
                merged['ActualTraffic']
                -
                merged['PredictedTraffic']
            )
            /
            merged['PredictedTraffic']
        )

        merged['is_deviation_anomaly'] = (
            merged['deviation']
            >
            ANOMALY_THRESHOLD
        )

        anomalies = merged[
            (
                merged['is_null_anomaly']
            )
            |
            (
                merged['is_deviation_anomaly']
            )
        ].copy()

        anomalies['site_name'] = site

        anomaly_list.append(anomalies)

        # Clear Memory
        tf.compat.v1.reset_default_graph()

    except Exception as e:

        print(f"Skipping {site}: {e}")

# Results Table
results_df = pd.DataFrame(results)

print("\n===== LSTM PERFORMANCE =====")
print(results_df)

