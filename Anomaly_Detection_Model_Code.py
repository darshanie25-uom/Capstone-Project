# Feature Engineering
def create_features(data):

    data = data.copy()

    # Time Features
    data['hour'] = data['datetime'].dt.hour
    data['dayofweek'] = data['datetime'].dt.dayofweek

    # Lag Features
    data['lag1'] = (
        data.groupby('site_name')
        ['sum_dl_traffic_volume_gb']
        .shift(1)
    )

    data['lag24'] = (
        data.groupby('site_name')
        ['sum_dl_traffic_volume_gb']
        .shift(24)
    )

    # Rolling Mean
    data['rolling_3'] = (
        data.groupby('site_name')
        ['sum_dl_traffic_volume_gb']
        .rolling(3)
        .mean()
        .reset_index(level=0, drop=True)
    )

    return data

# Apply feature engineering
df = create_features(df)

# Train and Validation Data Split
# TRAIN: 2nd -> 4th March
train_df = df[
    (df['date'] >= '2026-03-02') &
    (df['date'] <= '2026-03-04')
].copy()

# VALIDATION: 5th March
val_df = df[
    (df['date'] == '2026-03-05')
].copy()

# Remove NA generated from lagging
train_df = train_df.dropna()
val_df = val_df.dropna()


# Features and Traget Parameter
features = [
    'hour',
    'dayofweek',
    'sum_avg_connected_users',
    'sum_avg_dl_user_thp_qci_8_kbps_num',
    'sum_avg_dl_user_thp_qci_8_kbps_deno',
    'sum_avg_dl_user_thp_qci_9_kbps_num',
    'sum_avg_dl_user_thp_qci_9_kbps_deno',
    'lag1',
    'lag24',
    'rolling_3'
]

target = 'sum_dl_traffic_volume_gb'

# Train model per site
models = {}
results = []

site_list = train_df['site_name'].unique()

for site in site_list:

    # Train data
    site_train = train_df[
        train_df['site_name'] == site
    ]

    # Validation data
    site_val = val_df[
        val_df['site_name'] == site
    ]

    # Skip weak sites
    if len(site_train) < 24 or len(site_val) == 0:
        continue

    # Training the model
    X_train = site_train[features]
    y_train = site_train[target]

    model = XGBRegressor(
        n_estimators=100,
        max_depth=4,
        learning_rate=0.1,
        random_state=42
    )

    model.fit(X_train, y_train)

    models[site] = model

    # Validation
    X_val = site_val[features]
    y_val = site_val[target]

    y_pred = model.predict(X_val)

    # Generate Measuring Parameters
    mae = mean_absolute_error(y_val, y_pred)

    rmse = np.sqrt(
        mean_squared_error(y_val, y_pred)
    )

    r2 = r2_score(y_val, y_pred)

    results.append({
        'site_name': site,
        'MAE': mae,
        'RMSE': rmse,
        'R2': r2
    })

